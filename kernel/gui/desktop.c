unsigned desktop_calendar_days(unsigned year,unsigned month){
    if(month<1||month>12)return 0;
    static const uint8_t days[]={31,28,31,30,31,30,31,31,30,31,30,31};
    if(month==2 && ((year%4u==0 && year%100u!=0)||year%400u==0))return 29;
    return days[month-1];
}
unsigned desktop_calendar_weekday(unsigned year,unsigned month,unsigned day){
    /* Sakamoto's algorithm, Sunday=0; valid Gregorian dates only. */
    static const unsigned t[]={0,3,2,5,0,3,5,1,4,6,2,4};
    if(year<1600 || year>9999 || month<1||month>12||day<1||day>desktop_calendar_days(year,month))return 7;
    unsigned y=year-(month<3);
    return (y+y/4-y/100+y/400+t[month-1]+day)%7;
}
void desktop_native_show(desktop_t *d,unsigned slot,bool showing) {
    if(!d||slot>=NATIVE_MAX_WINDOWS)return;
    int index=DESKTOP_NATIVE+(int)slot;
    if(showing && !d->windows[index].open){
        d->windows[index].maximized=false;
        open_window(d,index);
    }
    if(showing){
        desktop_window_t *w=&d->windows[index];
        native_set_window_size(slot,(unsigned)w->w,(unsigned)w->h);
    }
    if(!showing && d->windows[index].open){
        desktop_window_t *w=&d->windows[index];
        if(w->maximized){
            w->x=w->restore_x;w->y=w->restore_y;
            w->w=w->restore_w;w->h=w->restore_h;
        }
        w->open=false;
        w->maximized=false;
    }
}
void desktop_native_sync(desktop_t *d,unsigned slot,const native_window_t *native){
    if(!d||!native||slot>=NATIVE_MAX_WINDOWS)return;
    if(!native->active){
        d->wm_seen_geometry[slot]=0;
        d->wm_seen_focus[slot]=0;
        return;
    }
    int index=DESKTOP_NATIVE+(int)slot;
    if(native->wm_geometry_serial && native->wm_geometry_serial!=d->wm_seen_geometry[slot]){
        d->wm_seen_geometry[slot]=native->wm_geometry_serial;
        desktop_window_t *w=&d->windows[index];
        /* Keep all titlebar controls visible inside the framebuffer. */
        if(native->wm_width>=120u && native->wm_height>=80u &&
           native->wm_x+native->wm_width<=(unsigned)d->surface->width &&
           native->wm_y+native->wm_height+42u<=(unsigned)d->surface->height){
            w->x=(int)native->wm_x;w->y=(int)native->wm_y;
            w->w=(int)native->wm_width;w->h=(int)native->wm_height;
            w->maximized=false;
        }
    }
    native_set_window_size(slot,(unsigned)d->windows[index].w,(unsigned)d->windows[index].h);
    if(native->wm_focus_serial && native->wm_focus_serial!=d->wm_seen_focus[slot]){
        d->wm_seen_focus[slot]=native->wm_focus_serial;
        if(d->windows[index].open)open_window(d,index);
    }
}

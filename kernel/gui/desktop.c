static bool run_equal(const char *a,const char *b) {
    for(;*a&&*b;++a,++b) {
        char c=*a>='A'&&*a<='Z'?(char)(*a+32):*a;
        char z=*b>='A'&&*b<='Z'?(char)(*b+32):*b;
        if(c!=z)return false;
    }
    return !*a&&!*b;
}
static void run_launch(desktop_t *d) {
    char command[sizeof(d->run_input)];
    size_t first=0,n=d->run_length;
    while(first<n && d->run_input[first]==' ')++first;
    while(n>first && d->run_input[n-1]==' ')--n;
    size_t used=n-first;
    if(!used)return;
    for(size_t i=0;i<used;++i){
        char ch=d->run_input[first+i];
        command[i]=ch>='A'&&ch<='Z'?(char)(ch+32):ch;
    }
    command[used]=0;
    static const char *const names[]={"cmd","explorer","about","notepad","calc","paint","taskmgr","control","mines","clock","snake","run","wordpad","calendar"};
    for(int i=0;i<DESKTOP_NATIVE;++i) {
        if(run_equal(command,names[i]) || run_equal(command,desktop_titles[i])) {
            open_window(d,i);d->windows[DESKTOP_RUN].open=false;
            d->run_status[0]=0;return;
        }
    }
    if(run_equal(command,"terminal")){open_window(d,DESKTOP_TERMINAL);d->windows[DESKTOP_RUN].open=false;return;}
    if(run_equal(command,"files")){open_window(d,DESKTOP_FILES);d->windows[DESKTOP_RUN].open=false;return;}
    if(run_equal(command,"write")){open_window(d,DESKTOP_WORDPAD);d->windows[DESKTOP_RUN].open=false;return;}
    if(run_equal(command,"calendar.exe")){open_window(d,DESKTOP_CALENDAR);d->windows[DESKTOP_RUN].open=false;return;}
    if(run_equal(command,"settings")){open_window(d,DESKTOP_SETTINGS);d->windows[DESKTOP_RUN].open=false;return;}
    /* Only existing, bundled initrd paths are handed to the prototype ELF loader. */
    if(used>4 && command[0]=='b' && command[1]=='i' && command[2]=='n' && command[3]=='/'){
        if(d->shell.services.run && d->shell.services.run(d->shell.services.ctx,command)){
            d->windows[DESKTOP_RUN].open=false;return;
        }
        const char *msg="COULD NOT RUN BUNDLED ELF";
        size_t i=0;while(msg[i]){d->run_status[i]=msg[i];++i;}d->run_status[i]=0;
        return;
    }
    const char *msg="UNKNOWN PROGRAM - TRY NOTEPAD OR CMD";
    size_t i=0;while(msg[i]){d->run_status[i]=msg[i];++i;}d->run_status[i]=0;
}

static void focus(desktop_t *d,int which) {
    int found=-1;
    for(int i=0;i<DESKTOP_WINDOWS;++i)if(d->order[i]==which)found=i;
    if(found<0)return;
    for(int i=found;i<DESKTOP_WINDOWS-1;++i)d->order[i]=d->order[i+1];
    d->order[DESKTOP_WINDOWS-1]=which;
}
int desktop_top_window(const desktop_t *d) {
    for(int i=DESKTOP_WINDOWS-1;i>=0;--i) {
        int idx=d->order[i];
        if(d->windows[idx].open&&!d->windows[idx].minimized)return idx;
    }
    return -1;
}
static void open_window(desktop_t *d,int which) {
    if(which<0||which>=DESKTOP_WINDOWS)return;
    desktop_window_t *w=&d->windows[which];
    /* Reopening a closed maximized window starts at its old normal size. */
    if(!w->open && w->maximized){
        w->x=w->restore_x;w->y=w->restore_y;
        w->w=w->restore_w;w->h=w->restore_h;
        w->maximized=false;
    }
    w->open=true;w->minimized=false;
    if(which==DESKTOP_TERMINAL)d->shell.visible=true;
    d->showing_desktop=false;
    focus(d,which);
}
bool desktop_shell_close(desktop_t *d){
    if(!d)return false;
    int top=desktop_top_window(d);
    if(top<0)return false;
    if(top>=DESKTOP_NATIVE){native_close_request_slot((unsigned)(top-DESKTOP_NATIVE));}
    else d->windows[top].open=false;
    return true;
}
void desktop_shell_desktop(desktop_t *d){if(d)show_desktop(d);}
bool desktop_shell_open(desktop_t *d,uint32_t index){
    if(!d||index>=DESKTOP_NATIVE)return false;
    /* Service-controlled launch; old built-in is the safe fallback. */
    /* Only switch Start-menu entries when the native replacement already
       covers the everyday controls. Other ELF pilots remain launchable via
       RUN BIN/NAME until they reach behavioral parity. */
    bool preferred=index==DESKTOP_NOTEPAD || index==DESKTOP_CALCULATOR ||
                   index==DESKTOP_MINES || index==DESKTOP_SNAKE ||
                   index==DESKTOP_CALENDAR || index==DESKTOP_PAINT ||
                   index==DESKTOP_WORDPAD || index==DESKTOP_TERMINAL ||
                   index==DESKTOP_FILES || index==DESKTOP_RUN ||
                   index==DESKTOP_SETTINGS;
    if(!preferred || !desktop_shell_launch_native(d,index))
        open_window(d,(int)index);
    return true;
}
bool desktop_shell_task(desktop_t *d,uint32_t index){
    if(!d||index>=DESKTOP_WINDOWS||!d->windows[index].open)return false;
    if(desktop_top_window(d)==(int)index)d->windows[index].minimized=true;
    else {d->windows[index].minimized=false;focus(d,(int)index);}
    return true;
}
bool desktop_shell_focus(desktop_t *d,uint32_t index){
    if(!d||index>=DESKTOP_WINDOWS||!d->windows[index].open)return false;
    d->windows[index].minimized=false;focus(d,(int)index);return true;
}
bool desktop_shell_launch_native(desktop_t *d,uint32_t index){
    if(!d || !d->shell.services.run)return false;
    /* No user-controlled executable path reaches the privileged launcher.
       Only built-in, immutable ELF images are accepted. The existing desktop
       remains a fallback if a native application cannot be created. */
    const char *path=NULL;
    if(index==DESKTOP_CALCULATOR)path="bin/calculator";
    else if(index==DESKTOP_NOTEPAD)path="bin/notepad";
    else if(index==DESKTOP_CLOCK)path="bin/clock";
    else if(index==DESKTOP_CALENDAR)path="bin/calendar";
    else if(index==DESKTOP_SNAKE)path="bin/snake";
    else if(index==DESKTOP_MINES)path="bin/mines";
    else if(index==DESKTOP_MONITOR)path="bin/monitor";
    else if(index==DESKTOP_ABOUT)path="bin/about";
    else if(index==DESKTOP_PAINT)path="bin/paint";
    else if(index==DESKTOP_WORDPAD)path="bin/wordpad";
    else if(index==DESKTOP_TERMINAL)path="bin/terminal";
    else if(index==DESKTOP_FILES)path="bin/filemanager";
    else if(index==DESKTOP_RUN)path="bin/run";
    else if(index==DESKTOP_SETTINGS)path="bin/settings";
    if(!path)return false;
    /* Do not report success if no native window slot can be allocated;
       callers may then show the existing kernel-hosted implementation. */
    unsigned active=0;
    for(unsigned slot=0;slot<NATIVE_MAX_WINDOWS;++slot)
        if(native_snapshot_slot(slot).active)++active;
    if(active==NATIVE_MAX_WINDOWS)return false;
    return d->shell.services.run(d->shell.services.ctx,path);
}
bool desktop_shell_move(desktop_t *d,uint32_t index,uint32_t x,uint32_t y){
    if(!d || !d->surface || index>=DESKTOP_WINDOWS ||
       !d->windows[index].open || d->windows[index].minimized)return false;
    desktop_window_t *w=&d->windows[index];
    /* No arithmetic overflow or off-screen movement. The untrusted shell
       selects geometry, but the trusted desktop validates its bounds. */
    if(x>(uint32_t)d->surface->width || y>(uint32_t)d->surface->height ||
       (uint32_t)w->w>(uint32_t)d->surface->width-x ||
       (uint32_t)w->h+42u>(uint32_t)d->surface->height-y)return false;
    w->x=(int)x;w->y=(int)y;return true;
}
/* User-driven resize, distinct from restoring/maximizing: never modify the
 * saved normal rectangle until the user explicitly maximizes. Validation
 * lives in Ring 0 even when windowd requests the change. */
bool desktop_shell_resize(desktop_t *d,uint32_t index,uint32_t width,uint32_t height){
    if(!d || !d->surface || index>=DESKTOP_WINDOWS)return false;
    desktop_window_t *w=&d->windows[index];
    if(!w->open || w->minimized || w->maximized)return false;
    /* Legacy UI uses several fixed controls; keep enough area for them.
     * Ring 3 apps use a virtual canvas and safely support smaller windows. */
    uint32_t min_width=index>=DESKTOP_NATIVE?240u:340u;
    uint32_t min_height=index>=DESKTOP_NATIVE?190u:280u;
    if(index==DESKTOP_CALCULATOR){min_width=270u;min_height=310u;}
    if(index==DESKTOP_RUN){min_width=340u;min_height=190u;}
    if(index==DESKTOP_ABOUT){min_width=340u;min_height=235u;}
    if(width<min_width || height<min_height ||
       (uint32_t)w->x>(uint32_t)d->surface->width ||
       (uint32_t)w->y>(uint32_t)d->surface->height-42u ||
       width>(uint32_t)d->surface->width-(uint32_t)w->x ||
       height>(uint32_t)d->surface->height-42u-(uint32_t)w->y)return false;
    w->w=(int)width;w->h=(int)height;
    if(index>=DESKTOP_NATIVE)native_set_window_size(index-DESKTOP_NATIVE,width,height);
    return true;
}
/* Maximize to the usable desktop, keeping the taskbar accessible.
 * Remember each window's previous geometry for lossless restoration.
 * Native fixed-resolution canvases are composited at a matching aspect-
 * preserving scale; their input is translated through the same viewport. */
bool desktop_shell_maximize(desktop_t *d,uint32_t index){
    if(!d || !d->surface || index>=DESKTOP_WINDOWS)return false;
    desktop_window_t *w=&d->windows[index];
    if(!w->open)return false;
    if(w->maximized){
        w->x=w->restore_x;w->y=w->restore_y;
        w->w=w->restore_w;w->h=w->restore_h;
        w->maximized=false;
    }else{
        if(d->surface->width<120 || d->surface->height<122)return false;
        w->restore_x=w->x;w->restore_y=w->y;
        w->restore_w=w->w;w->restore_h=w->h;
        w->x=0;w->y=0;w->w=d->surface->width;
        w->h=d->surface->height-42;
        w->maximized=true;
    }
    w->minimized=false;
    d->dragging=false;
    d->resizing=false;
    focus(d,(int)index);
    if(index>=DESKTOP_NATIVE)native_set_window_size(index-DESKTOP_NATIVE,(unsigned)w->w,(unsigned)w->h);
    return true;
}
const char *desktop_shell_title(desktop_t *d,uint32_t index){
    if(!d||index>=DESKTOP_WINDOWS)return "";
    if(index>=DESKTOP_NATIVE){
        /* Use stable generic native names. Window titles remain kernel-owned
         * and are rendered by the legacy window compositor. */
        return "Native app";
    }
    return desktop_titles[index];
}

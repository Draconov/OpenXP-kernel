void desktop_redraw_active(desktop_t *d){
    if(!d || d->start_open)return;
    int top=desktop_top_window(d);
    if(top<0)return;
#ifndef OPENXP_WM_HOST_TEST
    if(top>=DESKTOP_NATIVE && shell_bridge_raster_ready(OXP_SHELL_LAYER_NATIVE))
        return; /* windowd will publish the updated native pixels. */
#endif
    const desktop_window_t *w=&d->windows[top];
    desktop_present_region(d,w->x-1,w->y-1,w->w+8,w->h+8);
}
void desktop_redraw_paint(desktop_t *d){
    if(!d || !d->paint_dirty || desktop_top_window(d)!=DESKTOP_PAINT)return;
    const desktop_window_t *w=&d->windows[DESKTOP_PAINT];
    int x=w->x+16+(int)d->paint_min_x*2;
    int y=w->y+96+(int)d->paint_min_y*2;
    int width=((int)d->paint_max_x-(int)d->paint_min_x+1)*2;
    int height=((int)d->paint_max_y-(int)d->paint_min_y+1)*2;
    desktop_present_region(d,x,y,width,height);
    d->paint_dirty=false;
}
void desktop_redraw_terminal(desktop_t *d){
    if(d && desktop_top_window(d)==DESKTOP_TERMINAL)desktop_redraw_active(d);
}
static void open_preferred(desktop_t *d,int id){
#ifndef OPENXP_WM_HOST_TEST
    if((id==DESKTOP_NOTEPAD || id==DESKTOP_CALCULATOR ||
        id==DESKTOP_MINES || id==DESKTOP_SNAKE ||
        id==DESKTOP_CALENDAR) &&
       desktop_shell_launch_native(d,(uint32_t)id))return;
#endif
    open_window(d,id);
}
static void desktop_click(desktop_t *d,int x,int y) {
    int h=d->surface->height;
    if(y>=h-42) {
        if(x<110){d->start_open=!d->start_open;d->menu_selection=0;return;}
        int count=0,slot=0;
        for(int i=0;i<DESKTOP_WINDOWS;++i)if(d->windows[i].open)++count;
        int bw=count?(d->surface->width-216)/count:1;
        if(bw>142)bw=142;
        if(bw<1)bw=1;
        for(int i=0;i<DESKTOP_WINDOWS;++i) {
            if(!d->windows[i].open)continue;
            int bx=115+slot++*bw;
            if(x>=bx&&x<bx+bw-3) {
                if(desktop_top_window(d)==i)d->windows[i].minimized=true;
                else open_window(d,i);
                d->start_open=false;return;
            }
        }
        d->start_open=false;return;
    }
    if(d->start_open) {
        int top=h-42-370;
        for(int i=0;i<DESKTOP_NATIVE;++i) {
            if(inside(x,y,12+(i/7)*245,top+51+(i%7)*43,230,40)) {
                open_preferred(d,i);break;
            }
        }
        d->start_open=false;return;
    }
    /* Match windowd's published stacking order when choosing caption
       buttons; the fallback desktop uses the ordinary kernel order. */
    uint32_t shell_order[DESKTOP_WINDOWS];
    uint32_t shell_count=0;
    bool use_shell_order=false;
#ifndef OPENXP_WM_HOST_TEST
    use_shell_order=shell_bridge_window_order(shell_order,DESKTOP_WINDOWS,&shell_count);
#endif
    int count=use_shell_order?(int)shell_count:DESKTOP_WINDOWS;
    for(int z=count-1;z>=0;--z) {
        int i=use_shell_order?(int)shell_order[z]:d->order[z];
        desktop_window_t *w=&d->windows[i];
        if(!w->open||w->minimized||!inside(x,y,w->x,w->y,w->w,w->h))continue;
        if(y<w->y+33 && x>=w->x+w->w-31){
            if(i>=DESKTOP_NATIVE)native_close_request_slot((unsigned)(i-DESKTOP_NATIVE));
            else {w->open=false;}
            return;}
        if(y<w->y+33 && x>=w->x+w->w-57){
            (void)desktop_shell_maximize(d,(uint32_t)i);return;
        }
        if(y<w->y+33 && x>=w->x+w->w-83){w->minimized=true;return;}
        if(!w->maximized && x>=w->x+w->w-18 && y>=w->y+w->h-18){
            d->resizing=true;d->resize_window=i;
            d->last_x=x;d->last_y=y;
            focus(d,i);
            return;
        }
#ifndef OPENXP_WM_HOST_TEST
        if(shell_bridge_active())shell_bridge_notify_focus((uint32_t)i);
        else focus(d,i);
#else
        focus(d,i);
#endif
        if(i>=DESKTOP_NATIVE){
            unsigned xlocal=(unsigned)(x-w->x);
            unsigned ylocal=(unsigned)(y-w->y);
            oxp_native_pointer_to_canvas(xlocal,ylocal,(unsigned)w->w,
                                         (unsigned)w->h,&xlocal,&ylocal);
            native_push_event_slot((unsigned)(i-DESKTOP_NATIVE),
                NATIVE_EVENT_CLICK | ((xlocal&1023u)<<10) | (ylocal&1023u));
            return;
        }
        if(i==DESKTOP_PAINT){
            if(inside(x,y,w->x+16,w->y+54,8*38,26)){
                int color=(x-(w->x+16))/38;
                if(color>=0&&color<8)d->paint_color=(unsigned)color;
                return;
            }
            if(inside(x,y,w->x+16,w->y+w->h-35,75,23)){paint_clear(d);return;}
            if(inside(x,y,w->x+202,w->y+w->h-35,60,23)){save_paint(d);return;}
            if(inside(x,y,w->x+267,w->y+w->h-35,60,23)){open_paint(d);return;}
            if(inside(x,y,w->x+16,w->y+96,320,200)){
                d->paint_active=true;
                d->paint_last_x=(x-w->x-16)/2;d->paint_last_y=(y-w->y-96)/2;
                paint_set(d,d->paint_last_x,d->paint_last_y);
                return;
            }
        }
        if(i==DESKTOP_SETTINGS){
            for(unsigned index=0;index<3;++index)
                if(inside(x,y,w->x+18,w->y+105+(int)index*44,w->w-36,39)){
                    d->appearance=index;return;
                }
        }
        if(i==DESKTOP_MINES){
            if(inside(x,y,w->x+200,w->y+47,60,25)){mine_restart(d);return;}
            int cell=mine_cell_at(d,x,y);
            if(cell>=0){mine_reveal(d,cell);return;}
        }
        if(i==DESKTOP_CLOCK){
            if(inside(x,y,w->x+18,w->y+177,96,31)){clock_toggle(d);return;}
            if(inside(x,y,w->x+126,w->y+177,92,31)){clock_reset(d);return;}
            if(inside(x,y,w->x+230,w->y+177,95,31)){clock_mode(d);return;}
            if(inside(x,y,w->x+178,w->y+215,39,26)){clock_adjust(d,-1);return;}
            if(inside(x,y,w->x+235,w->y+215,39,26)){clock_adjust(d,1);return;}
        }
        if(i==DESKTOP_SNAKE && inside(x,y,w->x+275,w->y+44,91,27)){
            snake_reset(d);return;
        }
        if(i==DESKTOP_RUN){
            if(inside(x,y,w->x+w->w-215,w->y+w->h-44,90,29)){run_launch(d);return;}
            if(inside(x,y,w->x+w->w-111,w->y+w->h-44,91,29)){
                w->open=false;return;
            }
        }
        if(i==DESKTOP_FILES){
            if(inside(x,y,w->x+13,w->y+43,53,23)){file_up(d);return;}
            int rows=(w->h-170)/23;if(rows<1)rows=1;
            if(inside(x,y,w->x+12,w->y+108,w->w/2-20,rows*23)){
                int choice=(int)d->file_scroll+(y-(w->y+108))/23;
                if(choice<(int)file_items(d)){
                    bool dbl=d->selected_file==choice && d->clock_ticks-d->last_file_click<40;
                    file_select(d,choice);d->last_file_click=d->clock_ticks;
                    if(dbl)file_activate(d);
                }
                return;
            }
            if(inside(x,y,w->x+w->w-121,w->y+w->h-49,106,32)){
                file_activate(d);return;
            }
        }
        if(i==DESKTOP_NOTEPAD){
            if(inside(x,y,w->x+w->w-147,w->y+w->h-27,63,20)){save_note(d);return;}
            if(inside(x,y,w->x+w->w-79,w->y+w->h-27,63,20)){open_note(d);return;}
        }
        if(i==DESKTOP_WORDPAD){
            if(inside(x,y,w->x+w->w-151,w->y+w->h-31,65,24)){save_word(d);return;}
            if(inside(x,y,w->x+w->w-81,w->y+w->h-31,65,24)){open_word(d);return;}
            if(inside(x,y,w->x+13,w->y+43,61,28)){
                d->word_length=d->word_cursor=0;d->word[0]=0;return;
            }
            if(inside(x,y,w->x+82,w->y+43,45,28)){d->word_bold=!d->word_bold;return;}
            if(inside(x,y,w->x+136,w->y+43,31,28)){d->word_scale=1;return;}
            if(inside(x,y,w->x+176,w->y+43,31,28)){d->word_scale=2;return;}
        }
        if(i==DESKTOP_CALENDAR){
            if(inside(x,y,w->x+17,w->y+47,55,29)){calendar_month(d,-1);return;}
            if(inside(x,y,w->x+80,w->y+47,55,29)){calendar_month(d,1);return;}
            if(inside(x,y,w->x+w->w-93,w->y+47,71,29)){
                if(d->calendar_has_today){d->calendar_year=d->today_year;d->calendar_month=d->today_month;d->calendar_day=d->today_day;}return;
            }
            int first=(int)((desktop_calendar_weekday(d->calendar_year,d->calendar_month,1)+6)%7);
            int gx=w->x+25,gy=w->y+143,step=(w->w-51)/7;
            if(inside(x,y,gx,gy,step*7,180)){
                int index=((y-gy)/30)*7+(x-gx)/step;
                int day=index-first+1;
                if(day>=1 && day<=(int)desktop_calendar_days(d->calendar_year,d->calendar_month))d->calendar_day=(unsigned)day;
                return;
            }
        }
        if(i==DESKTOP_CALCULATOR && inside(x,y,w->x+13,w->y+96,w->w-25,184)) {
            int cell=(w->w-30)/4;
            int col=(x-(w->x+13))/cell,row=(y-(w->y+96))/46;
            static const char *keys[4]={"789/","456*","123-","C0=+"};
            if(row>=0&&row<4&&col>=0&&col<4 && (x-(w->x+13))%cell<cell-5)
                calculator_press(d,keys[row][col]);
            return;
        }
        if(y<w->y+33 && !w->maximized){d->dragging=true;d->drag_window=i;d->last_x=x;d->last_y=y;}
        return;
    }
    if(inside(x,y,12,25,104,65))open_window(d,DESKTOP_FILES);
    else if(inside(x,y,12,115,104,65))open_window(d,DESKTOP_FILES);
    else if(inside(x,y,12,205,104,65))open_window(d,DESKTOP_TERMINAL);
}
void desktop_mouse(desktop_t *d,int x,int y,bool down) {
    if(!d||!d->surface)return;
    if(x<0)x=0;
    if(y<0)y=0;
    if(x>=d->surface->width)x=d->surface->width-1;
    if(y>=d->surface->height)y=d->surface->height-1;
    if(down&&!d->mouse_down)desktop_click(d,x,y);
    else if(down && d->paint_active && desktop_top_window(d)==DESKTOP_PAINT){
        desktop_window_t *w=&d->windows[DESKTOP_PAINT];
        int px=(x-w->x-16)/2,py=(y-w->y-96)/2;
        if(inside(x,y,w->x+16,w->y+96,320,200)){
            paint_line(d,d->paint_last_x,d->paint_last_y,px,py);
            d->paint_last_x=px;d->paint_last_y=py;
        } else d->paint_active=false;
    }
    else if(down && d->resizing){
        desktop_window_t *w=&d->windows[d->resize_window];
        int nw=w->w+x-d->last_x,nh=w->h+y-d->last_y;
        if(nw>0 && nh>0)
            (void)desktop_shell_resize(d,(uint32_t)d->resize_window,
                                       (uint32_t)nw,(uint32_t)nh);
        d->last_x=x;d->last_y=y;
    }
    else if(down && d->dragging) {
        desktop_window_t *w=&d->windows[d->drag_window];
        int nx=w->x+x-d->last_x,ny=w->y+y-d->last_y;
        if(nx<0)nx=0;
        if(ny<0)ny=0;
        if(nx+w->w>d->surface->width)nx=d->surface->width-w->w;
        if(ny+w->h>d->surface->height-42)ny=d->surface->height-42-w->h;
        w->x=nx;w->y=ny;d->last_x=x;d->last_y=y;
    }
    if(!down){d->dragging=false;d->resizing=false;d->paint_active=false;}
    d->mouse_down=down;
    d->mouse_x=x;d->mouse_y=y;
}
void desktop_right_mouse(desktop_t *d,int x,int y,bool down){
    if(!d)return;
    if(down && !d->right_down && desktop_top_window(d)>=DESKTOP_NATIVE){
        int top=desktop_top_window(d);
        desktop_window_t *w=&d->windows[top];
        if(inside(x,y,w->x,w->y,w->w,w->h))
        {
            uint32_t cx=(uint32_t)(x-w->x),cy=(uint32_t)(y-w->y);
            oxp_native_pointer_to_canvas(cx,cy,(unsigned)w->w,(unsigned)w->h,&cx,&cy);
            native_push_event_slot((unsigned)(top-DESKTOP_NATIVE),
                NATIVE_EVENT_RIGHT_CLICK | (cx<<10) | cy);
        }
    }else if(down && !d->right_down && desktop_top_window(d)==DESKTOP_MINES)
        mine_toggle_flag(d,mine_cell_at(d,x,y));
    d->right_down=down;
}
void desktop_key(desktop_t *d,char c) {
    if(c=='\t') {
        for(int i=0;i<DESKTOP_WINDOWS;++i) {
            int idx=d->order[i];
            if(d->windows[idx].open&&!d->windows[idx].minimized){focus(d,idx);break;}
        }
        return;
    }
    if(desktop_top_window(d)==DESKTOP_TERMINAL) {
        (void)shell_key(&d->shell,c);
        if(!d->shell.visible)d->windows[DESKTOP_TERMINAL].minimized=true;
    }
}
static void show_desktop(desktop_t *d) {
    if(!d->showing_desktop) {
        for(int i=0;i<DESKTOP_WINDOWS;++i) {
            d->saved_minimized[i]=d->windows[i].minimized;
            d->windows[i].minimized=true;
        }
        d->showing_desktop=true;
    } else {
        for(int i=0;i<DESKTOP_WINDOWS;++i)
            d->windows[i].minimized=d->saved_minimized[i];
        d->showing_desktop=false;
    }
    d->start_open=false;
}
static void switch_window(desktop_t *d) {
    int top=desktop_top_window(d);
    for(int z=DESKTOP_WINDOWS-1;z>=0;--z) {
        int idx=d->order[z];
        if(idx!=top && d->windows[idx].open && !d->windows[idx].minimized) {
            focus(d,idx);return;
        }
    }
}
void desktop_key_event(desktop_t *d,const input_event_t *event) {
    if(!d||!event||event->kind!=INPUT_KEY)return;
    uint8_t mods=event->modifiers;
    char c=event->key;
    char lc=(c>='A'&&c<='Z')?(char)(c+32):c;
    if(event->code==KEY_WINDOWS ||
       (event->code==KEY_ESCAPE && (mods&KEYMOD_CTRL))) {
        d->start_open=!d->start_open;
        d->menu_selection=0;
        return;
    }
    if((mods&KEYMOD_WIN) && (event->code==KEY_UP || event->code==KEY_DOWN)){
        int top=desktop_top_window(d);
        if(top>=0){
            desktop_window_t *w=&d->windows[top];
            if(event->code==KEY_UP && !w->maximized)
                (void)desktop_shell_maximize(d,(uint32_t)top);
            else if(event->code==KEY_DOWN){
                if(w->maximized)(void)desktop_shell_maximize(d,(uint32_t)top);
                else w->minimized=true;
            }
        }
        return;
    }
    if(mods&KEYMOD_WIN) {
        switch(lc) {
        case 'e':open_window(d,DESKTOP_FILES);d->start_open=false;return;
        case 'r':open_window(d,DESKTOP_RUN);d->start_open=false;return;
        case 't':open_window(d,DESKTOP_TERMINAL);d->start_open=false;return;
        case 'k':open_preferred(d,DESKTOP_CLOCK);d->start_open=false;return;
        case 'y':open_preferred(d,DESKTOP_SNAKE);d->start_open=false;return;
        case 'w':open_window(d,DESKTOP_WORDPAD);d->start_open=false;return;
        case 'a':open_preferred(d,DESKTOP_CALENDAR);d->start_open=false;return;
        case 'd':show_desktop(d);return;
        case 'n':open_preferred(d,DESKTOP_NOTEPAD);d->start_open=false;return;
        case 'c':open_preferred(d,DESKTOP_CALCULATOR);d->start_open=false;return;
        case 'p':open_window(d,DESKTOP_PAINT);d->start_open=false;return;
        case 'm':open_preferred(d,DESKTOP_MONITOR);d->start_open=false;return;
        case 's':open_window(d,DESKTOP_SETTINGS);d->start_open=false;return;
        case 'g':open_preferred(d,DESKTOP_MINES);d->start_open=false;return;
        default: break;
        }
    }
    if(mods&KEYMOD_ALT) {
        if(event->code==KEY_TAB){switch_window(d);d->start_open=false;return;}
        if(event->code==KEY_F4){
            int top=desktop_top_window(d);
            if(top>=DESKTOP_NATIVE)native_close_request_slot((unsigned)(top-DESKTOP_NATIVE));
            else if(top>=0)d->windows[top].open=false;
            d->start_open=false;return;
        }
    }
    if(event->code==KEY_ESCAPE) {
        int top=desktop_top_window(d);
        if(top>=DESKTOP_NATIVE) {native_push_event_slot((unsigned)(top-DESKTOP_NATIVE),27);return;}
        if(desktop_top_window(d)==DESKTOP_RUN)d->windows[DESKTOP_RUN].open=false;
        d->start_open=false;return;
    }
    if(d->start_open) {
        if(event->code==KEY_UP) {
            d->menu_selection=(d->menu_selection/7)*7+(d->menu_selection%7+6)%7;return;
        }
        if(event->code==KEY_DOWN) {
            d->menu_selection=(d->menu_selection/7)*7+(d->menu_selection%7+1)%7;return;
        }
        if(event->code==KEY_RIGHT && d->menu_selection<7 && d->menu_selection+7<DESKTOP_NATIVE){d->menu_selection+=7;return;}
        if(event->code==KEY_LEFT && d->menu_selection>=7){d->menu_selection-=7;return;}
        if(event->code==KEY_ENTER) {
            open_window(d,(int)d->menu_selection);d->start_open=false;return;
        }
        /* Typing while the Start menu is visible must not leak into Terminal. */
        return;
    }
    /* Single-key Save/Open actions do not depend on keyboard layout case. */
    if(mods&KEYMOD_CTRL) {
        int top=desktop_top_window(d);
        if(lc=='s') {
            if(top==DESKTOP_NOTEPAD)save_note(d);
            else if(top==DESKTOP_WORDPAD)save_word(d);
            else if(top==DESKTOP_PAINT)save_paint(d);
            if(top==DESKTOP_NOTEPAD || top==DESKTOP_WORDPAD || top==DESKTOP_PAINT)return;
        }
        if(lc=='o') {
            if(top==DESKTOP_NOTEPAD)open_note(d);
            else if(top==DESKTOP_WORDPAD)open_word(d);
            else if(top==DESKTOP_PAINT)open_paint(d);
            if(top==DESKTOP_NOTEPAD || top==DESKTOP_WORDPAD || top==DESKTOP_PAINT)return;
        }
    }
    if(desktop_top_window(d)>=DESKTOP_NATIVE){
        unsigned slot=(unsigned)(desktop_top_window(d)-DESKTOP_NATIVE);
        if(mods&KEYMOD_CTRL) {
            if(lc=='s')native_push_event_slot(slot,NATIVE_EVENT_SAVE);
            else if(lc=='o')native_push_event_slot(slot,NATIVE_EVENT_OPEN);
            return;
        }
        if(event->code==KEY_UP)native_push_event_slot(slot,NATIVE_EVENT_UP);
        else if(event->code==KEY_DOWN)native_push_event_slot(slot,NATIVE_EVENT_DOWN);
        else if(event->code==KEY_LEFT)native_push_event_slot(slot,NATIVE_EVENT_LEFT);
        else if(event->code==KEY_RIGHT)native_push_event_slot(slot,NATIVE_EVENT_RIGHT);
        else if(event->code==KEY_ENTER)native_push_event_slot(slot,'\n');
        else if(event->code==KEY_BACKSPACE)native_push_event_slot(slot,8);
        else if(event->code==KEY_ESCAPE)native_push_event_slot(slot,27);
        else if(event->code==KEY_CHARACTER && !(mods&(KEYMOD_CTRL|KEYMOD_ALT|KEYMOD_WIN)) && (unsigned char)c>=32)
            native_push_event_slot(slot,(unsigned char)c);
        return;
    }
    if(desktop_top_window(d)==DESKTOP_RUN){run_key(d,event);return;}
    if(desktop_top_window(d)==DESKTOP_CLOCK){
        if(c==' '||lc=='s')clock_toggle(d);
        else if(lc=='r')clock_reset(d);
        else if(lc=='m')clock_mode(d);
        else if(c=='+')clock_adjust(d,1);
        else if(c=='-')clock_adjust(d,-1);
        return;
    }
    if(desktop_top_window(d)==DESKTOP_SNAKE){
        unsigned dir=4;
        if(event->code==KEY_UP)dir=0;
        else if(event->code==KEY_RIGHT)dir=1;
        else if(event->code==KEY_DOWN)dir=2;
        else if(event->code==KEY_LEFT)dir=3;
        if(dir<4)snake_turn(d,dir);
        else if(lc=='n')snake_reset(d);
        else if(c==' '||lc=='p'){
            if(d->snake_started && !d->snake_lost && !d->snake_won){
                d->snake_paused=!d->snake_paused;d->snake_last_step=d->clock_ticks;
            } else if(!d->snake_lost && !d->snake_won) {
                d->snake_started=true;d->snake_last_step=d->clock_ticks;
            }
        }
        return;
    }
    if(desktop_top_window(d)==DESKTOP_SETTINGS){
        if(c>='1'&&c<='3')d->appearance=(unsigned)(c-'1');
        return;
    }
    if(desktop_top_window(d)==DESKTOP_MINES){
        if(lc=='n')mine_restart(d);
        if(lc=='f')mine_toggle_flag(d,mine_cell_at(d,d->mouse_x,d->mouse_y));
        return;
    }
    if(desktop_top_window(d)==DESKTOP_PAINT){
        if(lc=='x')paint_clear(d);
        else if(c>='1'&&c<='8')d->paint_color=(unsigned)(c-'1');
        return;
    }
    if(desktop_top_window(d)==DESKTOP_NOTEPAD){note_key(d,event);return;}
    if(desktop_top_window(d)==DESKTOP_CALCULATOR){
        if(event->code==KEY_ENTER)calculator_press(d,'=');
        else if(!(mods&(KEYMOD_CTRL|KEYMOD_ALT|KEYMOD_WIN)))calculator_press(d,c);
        return;
    }
    if(desktop_top_window(d)==DESKTOP_FILES){
        if(event->code==KEY_BACKSPACE){file_up(d);return;}
        if(event->code==KEY_UP){if(d->selected_file>0)file_select(d,d->selected_file-1);return;}
        if(event->code==KEY_DOWN){
            if(d->selected_file+1<(int)file_items(d))file_select(d,d->selected_file+1);
            return;
        }
        if(event->code==KEY_HOME){if(file_items(d))file_select(d,0);return;}
        if(event->code==KEY_END){unsigned n=file_items(d);if(n)file_select(d,(int)n-1);return;}
        if(event->code==KEY_ENTER){file_activate(d);return;}
        return;
    }
    if(desktop_top_window(d)==DESKTOP_WORDPAD){word_key(d,event);return;}
    if(desktop_top_window(d)==DESKTOP_CALENDAR){
        if(event->code==KEY_LEFT)calendar_month(d,-1);
        else if(event->code==KEY_RIGHT)calendar_month(d,1);
        else if(event->code==KEY_UP && d->calendar_year<9999){++d->calendar_year;}
        else if(event->code==KEY_DOWN && d->calendar_year>1600){--d->calendar_year;}
        else if(lc=='t' && d->calendar_has_today){d->calendar_year=d->today_year;d->calendar_month=d->today_month;d->calendar_day=d->today_day;}
        unsigned days=desktop_calendar_days(d->calendar_year,d->calendar_month);
        if(d->calendar_day>days)d->calendar_day=days;
        return;
    }
    if(desktop_top_window(d)!=DESKTOP_TERMINAL)return;
    if((mods&KEYMOD_CTRL) && lc=='l') {
        shell_execute(&d->shell,"cls");return;
    }
    if((mods&KEYMOD_CTRL) && lc=='c') {
        d->shell.used=0;d->shell.input[0]=0;return;
    }
    if(event->code==KEY_UP) {shell_history(&d->shell,-1);return;}
    if(event->code==KEY_DOWN) {shell_history(&d->shell,1);return;}
    if(event->code==KEY_HOME) {shell_home(&d->shell);return;}
    if(event->code==KEY_END) {shell_end(&d->shell);return;}
    if(event->code==KEY_LEFT) {shell_left(&d->shell);return;}
    if(event->code==KEY_RIGHT) {shell_right(&d->shell);return;}
    if(event->code==KEY_DELETE) {shell_delete(&d->shell);return;}
    if(!(mods&(KEYMOD_CTRL|KEYMOD_ALT|KEYMOD_WIN)) && c)
        desktop_key(d,c);
}
void desktop_tick(desktop_t *d,uint64_t ticks){
    if(!d)return;
    d->clock_ticks=ticks;
    if(d->watch_countdown && d->watch_running && stopwatch_elapsed(d)>=d->watch_limit){
        d->watch_elapsed=d->watch_limit;
        d->watch_running=false;
        d->watch_alarm=true;
    }
    if(d->snake_started && !d->snake_paused && !d->snake_lost && !d->snake_won){
        /* Background windows cannot silently lose the game while unfocused. */
        if(desktop_top_window(d)!=DESKTOP_SNAKE){d->snake_last_step=ticks;return;}
        if(ticks-d->snake_last_step>=18){
            d->snake_last_step=ticks;
            snake_step(d);
        }
    }
}

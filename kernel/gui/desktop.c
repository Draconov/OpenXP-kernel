/* The OXRD archive has no real directories; the file manager synthesizes
 * folders from path components, avoiding writable filesystem assumptions. */
typedef struct { char name[48],path[48]; bool folder; } file_item_t;
static void copy_str(char *out,size_t cap,const char *src){
    if(!cap)return;
    size_t i=0;while(src[i] && i+1<cap){out[i]=src[i];++i;}out[i]=0;
}
static bool file_item(desktop_t *d,unsigned index,file_item_t *entry){
    unsigned found=0;
    size_t prefix=0;while(d->file_folder[prefix])++prefix;
    size_t total=d->shell.services.file_count?d->shell.services.file_count(d->shell.services.ctx):
        initrd_count()+ramfs_count();
    for(size_t k=0;k<total;++k){
        char full[64];
        bool got=d->shell.services.file_name?
            d->shell.services.file_name(d->shell.services.ctx,k,full,sizeof(full)):
            (k<initrd_count()?initrd_name_at(k,full,sizeof(full)):
             ramfs_name_at(k-initrd_count(),full,sizeof(full)));
        if(!got)continue;
        size_t z=0;
        while(z<prefix && full[z] && full[z]==d->file_folder[z])++z;
        if(z!=prefix || (prefix && full[z]!='/'))continue;
        const char *tail=full+prefix+(prefix?1:0);
        if(!*tail)continue;
        size_t name_len=0;
        while(tail[name_len] && tail[name_len]!='/' && name_len<47)++name_len;
        bool directory=tail[name_len]=='/';
        if(!name_len || name_len>=48)continue;
        /* A directory can contain multiple entries; report it once. */
        if(directory){
            bool duplicate=false;
            for(size_t previous=0;previous<k;++previous){
                char other[64];
                bool got_prev=d->shell.services.file_name?
                    d->shell.services.file_name(d->shell.services.ctx,previous,other,sizeof(other)):
                    (previous<initrd_count()?initrd_name_at(previous,other,sizeof(other)):
                     ramfs_name_at(previous-initrd_count(),other,sizeof(other)));
                if(!got_prev)continue;
                const char *prior=other+prefix+(prefix?1:0);
                size_t i=0;while(i<prefix && other[i]==d->file_folder[i])++i;
                if(i!=prefix || (prefix && other[i]!='/'))continue;
                size_t n=0;while(prior[n] && prior[n]!='/' && n<48)++n;
                if(n==name_len && prior[n]=='/'){
                    size_t t=0;while(t<n && prior[t]==tail[t])++t;
                    if(t==n){duplicate=true;break;}
                }
            }
            if(duplicate)continue;
        }
        if(found++!=index)continue;
        size_t c=0;for(;c<name_len;++c)entry->name[c]=tail[c];entry->name[c]=0;
        entry->folder=directory;
        size_t a=0;
        for(;a<prefix;++a)entry->path[a]=d->file_folder[a];
        if(prefix)entry->path[a++]='/';
        for(size_t j=0;j<name_len && a+1<sizeof(entry->path);++j)entry->path[a++]=tail[j];
        entry->path[a]=0;return true;
    }
    return false;
}
static unsigned file_items(desktop_t *d){
    file_item_t it;unsigned count=0;
    while(count<INITRD_MAX_FILES+RAMFS_MAX_FILES && file_item(d,count,&it))++count;
    return count;
}
